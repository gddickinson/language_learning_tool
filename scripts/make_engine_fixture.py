"""Write tests/fixtures/engine_cases.json: the repo's Python pipeline (AudioProcessor, DTWComparator,
alignment_utils, feedback_report; librosa / fastdtw / scipy underneath) run on the synthetic signals of
web/static/synth.js. web/static/engine.test.mjs checks the JS port against it; tests/test_web.py checks it is current.

Run: python scripts/make_engine_fixture.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import librosa  # noqa: E402

from alignment_utils import apply_dtw_warping, calculate_path_smoothness  # noqa: E402
from audio_processor import AudioProcessor  # noqa: E402
from dtw_comparator import DTWComparator  # noqa: E402
from feedback_report import practice_report  # noqa: E402

SR = 44100
OUT = ROOT / "tests" / "fixtures" / "engine_cases.json"
# Same as PRESETS in web/static/synth.js
PRESETS = {
    "reference": dict(seconds=0.9, f0a=140, f0b=190, syl=2, harm=[1, 0.6, 0.35, 0.2, 0.1], noise=0.01, seed=1, pad=0),
    "close": dict(seconds=1.05, f0a=146, f0b=196, syl=2, harm=[1, 0.55, 0.4, 0.2, 0.1], noise=0.01, seed=2, pad=0),
    "different": dict(seconds=0.7, f0a=260, f0b=210, syl=3, harm=[1, 0.1, 0.5, 0.05, 0.3], noise=0.03, seed=3, pad=0),
    "padded": dict(seconds=0.9, f0a=140, f0b=190, syl=2, harm=[1, 0.6, 0.35, 0.2, 0.1], noise=0.01, seed=1, pad=0.3),
}


def mulberry32(seed):
    a = seed & 0xFFFFFFFF

    def imul(x, y):
        return ((x & 0xFFFFFFFF) * (y & 0xFFFFFFFF)) & 0xFFFFFFFF

    def nxt():
        nonlocal a
        a = (a + 0x6D2B79F5) & 0xFFFFFFFF
        t = imul(a ^ (a >> 15), 1 | a)
        t = ((t + imul(t ^ (t >> 7), 61 | t)) & 0xFFFFFFFF) ^ t
        return ((t ^ (t >> 14)) & 0xFFFFFFFF) / 4294967296
    return nxt


def synth(p, sr=SR):
    """Port of synth() in web/static/synth.js (scalar loop so the arithmetic order matches)."""
    n, npad = round(p["seconds"] * sr), round(p["pad"] * sr)
    out = np.zeros(n + 2 * npad)
    r, k = mulberry32(p["seed"]), (p["f0b"] - p["f0a"]) / p["seconds"]
    for i in range(n):
        t = i / sr
        phase = p["f0a"] * t + 0.5 * k * t * t
        env = 0.15 + np.sin(np.pi * p["syl"] * t / p["seconds"]) ** 2
        s = 0.0
        for h, a in enumerate(p["harm"]):
            s += a * np.sin(2 * np.pi * (h + 1) * phase)
        out[npad + i] = 0.4 * env * s + p["noise"] * (2 * r() - 1)
    return out


def _m(a):
    return np.asarray(a, dtype=float).tolist()


def build():
    proc, comp = AudioProcessor(), DTWComparator()
    sig = {k: synth(v) for k, v in PRESETS.items()}
    clips = {}
    for name in ("reference", "close", "different"):
        y = sig[name]
        S = np.abs(librosa.stft(y)) ** 2
        f, t, spec = proc.get_spectrogram(y)
        pitches = librosa.piptrack(y=y, sr=SR)[0]
        clips[name] = {
            "n": len(y),
            "head": _m(y[:5]),
            "mfcc": _m(comp.extract_features(y, "mfcc")),
            "chroma": _m(comp.extract_features(y, "chroma")),
            "spectral": _m(comp.extract_features(y, "spectral")),
            "tuning": float(librosa.estimate_tuning(S=S, sr=SR, bins_per_octave=12)),
            "mean_pitch": float(np.mean(pitches[pitches > 0])),
            "spectrogram": {"shape": list(spec.shape), "times": _m(t), "rows": _m(spec[::64, :])},
            "audio_features": {k: float(v) for k, v in proc.get_audio_features(y).items()},
        }
    trimmed = proc.trim_silence(sig["padded"])
    _, idx = librosa.effects.trim(sig["padded"], top_db=40)
    pairs = {}
    for user in ("close", "different", "reference"):
        u, ref = sig[user], sig["reference"]
        res = comp.compare_multiple_features(u, ref)
        ana = comp.analyze_pronunciation_errors(u, ref)
        paths = {ft: comp.compare_dtw(u, ref, ft)[1].tolist() for ft in ("mfcc", "chroma", "spectral")}
        un, rn = proc.normalize_audio(u), proc.normalize_audio(ref)
        warped = apply_dtw_warping(un, rn, paths["mfcc"])
        sm = calculate_path_smoothness(paths["mfcc"])
        corr = float(np.corrcoef(rn, warped)[0, 1])
        quality = "Excellent" if sm > 0.5 else "Good" if sm > 0.3 else "Fair" if sm > 0.15 else "Poor"
        score = res["similarity_score"]
        pairs[user] = {
            "results": {k: (bool(v) if isinstance(v, (bool, np.bool_)) else float(v)) for k, v in res.items()},
            "analysis": {k: (v if isinstance(v, str) else float(v)) for k, v in ana.items()},
            "paths": paths,
            "smoothness": float(sm),
            "correlation": corr,
            "warped_every_97": _m(warped[::97]),
            "report": practice_report(score, corr, quality, len(u) / len(ref), res, ana,
                                      comp.get_similarity_feedback(score)),
        }
    return {
        "note": "Generated by scripts/make_engine_fixture.py from the repo's Python code; do not edit by hand.",
        "versions": {"librosa": librosa.__version__, "numpy": np.__version__},
        "presets": PRESETS,
        "clips": clips,
        "trim": {"n_in": len(sig["padded"]), "start": int(idx[0]), "end": int(idx[1]), "n_out": len(trimmed)},
        "pairs": pairs,
    }


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(build(), separators=(",", ":")))
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e3:.0f} kB)")


if __name__ == "__main__":
    main()
